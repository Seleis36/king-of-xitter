#!/usr/bin/env python3
"""Convert the leader portraits in assets/portraits into Android VectorDrawables.

Usage: python3 tools/convert_portraits.py [--check]

Each assets/portraits/<name>.svg becomes app/src/main/res/drawable/portrait_<name>.xml.
The portraits use one <g> with shared stroke attributes, plus path/ellipse/circle/rect
children; groups are flattened by inheriting those attributes. Dashed strokes, which
VectorDrawable can't draw, are split into dash segments. With --check, the script fails if a
generated file differs, which keeps the drawables honest in CI.
"""

import glob
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "portraits")
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

INHERITED = ("stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill", "opacity")


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def color(value):
    if value in (None, "none"):
        return None
    return "#FF" + value.lstrip("#").upper()


def ellipse_path(a):
    cx, cy = float(a["cx"]), float(a["cy"])
    rx = float(a.get("rx") or a["r"])
    ry = float(a.get("ry") or a["r"])
    return (
        f"M{cx - rx:g},{cy:g}a{rx:g},{ry:g} 0,1 1,{2 * rx:g},0"
        f"a{rx:g},{ry:g} 0,1 1,{-2 * rx:g},0z"
    )


def rect_path(a):
    x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
    return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z"


def dash_path(data, dash, gap):
    """Split M/L subpaths into dash segments along their length."""
    out = []
    for subpath in re.findall(r"M[^M]*", data):
        nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", subpath)]
        points = list(zip(nums[0::2], nums[1::2]))
        pos, drawing, remaining = 0.0, True, dash
        for (x1, y1), (x2, y2) in zip(points, points[1:]):
            length = math.hypot(x2 - x1, y2 - y1)
            start = 0.0
            while start < length - 1e-6:
                step = min(remaining, length - start)
                if drawing:
                    t0, t1 = start / length, (start + step) / length
                    out.append(
                        f"M{x1 + (x2 - x1) * t0:.2f},{y1 + (y2 - y1) * t0:.2f}"
                        f"L{x1 + (x2 - x1) * t1:.2f},{y1 + (y2 - y1) * t1:.2f}"
                    )
                start += step
                remaining -= step
                if remaining <= 1e-6:
                    drawing = not drawing
                    remaining = dash if drawing else gap
    return "".join(out)


def path_element(a):
    tag, element = a
    merged = element
    data = {
        "path": lambda: merged["d"],
        "ellipse": lambda: ellipse_path(merged),
        "circle": lambda: ellipse_path(merged),
        "rect": lambda: rect_path(merged),
    }[tag]()
    fill, stroke = color(merged.get("fill")), color(merged.get("stroke"))
    alpha = merged.get("opacity")
    lines = ["    <path"]
    if fill:
        lines.append(f'        android:fillColor="{fill}"')
        if alpha:
            lines.append(f'        android:fillAlpha="{float(alpha):g}"')
    if stroke and float(merged.get("stroke-width", 0)) > 0:
        lines.append(f'        android:strokeColor="{stroke}"')
        lines.append(f'        android:strokeWidth="{float(merged["stroke-width"]):g}"')
        if alpha:
            lines.append(f'        android:strokeAlpha="{float(alpha):g}"')
        lines.append(f'        android:strokeLineCap="{merged.get("stroke-linecap", "round")}"')
        lines.append(f'        android:strokeLineJoin="{merged.get("stroke-linejoin", "round")}"')
    lines.append(f'        android:pathData="{data}" />')
    return "\n".join(lines)


def elements(svg):
    """Flatten the portrait's single <g> by pushing its attributes onto each child."""
    inherited = {}
    out = []
    for tag, element in re.findall(r"<(g|path|ellipse|circle|rect)\b([^>]*)>", svg):
        a = attrs(element)
        if tag == "g":
            inherited = {k: v for k, v in a.items() if k in INHERITED}
            continue
        merged = dict(inherited)
        merged.update(a)
        if "stroke-dasharray" in merged:
            dash, gap = (float(v) for v in merged.pop("stroke-dasharray").split())
            merged["d"] = dash_path(merged["d"], dash, gap)
        out.append((tag, merged))
    return out


def vector(svg):
    _, _, vw, vh = (float(v) for v in attrs(re.search(r"<svg([^>]*)>", svg).group(1))["viewBox"].split())
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/convert_portraits.py from assets/portraits. Don't edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{vw:g}dp"',
        f'    android:height="{vh:g}dp"',
        f'    android:viewportWidth="{vw:g}"',
        f'    android:viewportHeight="{vh:g}">',
    ]
    lines += [path_element(element) for element in elements(svg)]
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    sources = sorted(glob.glob(os.path.join(SRC, "*.svg")))
    if not sources:
        raise SystemExit(f"no portraits in {SRC}")
    stale = []
    for source in sources:
        name = os.path.splitext(os.path.basename(source))[0]
        content = vector(open(source, encoding="utf-8").read())
        target = os.path.join(OUT, f"portrait_{name}.xml")
        if check:
            if not os.path.exists(target) or open(target, encoding="utf-8").read() != content:
                stale.append(target)
        else:
            with open(target, "w", encoding="utf-8") as f:
                f.write(content)
    if stale:
        raise SystemExit("stale portraits: " + ", ".join(stale))
    print(f"{len(sources)} portraits {'checked' if check else 'written'} in {OUT}")


if __name__ == "__main__":
    main()
