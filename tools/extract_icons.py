#!/usr/bin/env python3
"""Extract the design's inline SVG icons into Android VectorDrawables.

Usage: python3 tools/extract_icons.py [--check]

Icons are found by a unique prefix of their first path data in design/screens/*.html and written
to app/src/main/res/drawable/ic_<name>.xml. Icons drawn with `currentColor` become tintable
(black strokes/fills that Compose tints). Dashed strokes, which VectorDrawable can't draw, are
split into separate dash segments. With --check, the script fails if a generated file differs.
"""

import glob
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

# name -> prefix of the first drawn element's path data (or a unique attribute snippet).
