INK_TINT = "#FF000000"


def find_svg(snippet):
    for path in sorted(glob.glob(os.path.join(ROOT, "design", "screens", "*.html"))):
        html = open(path, encoding="utf-8").read()
        html = re.sub(r"<style.*?</style>", "", html, flags=re.S)
        for match in re.finditer(r"<svg([^>]*)>(.*?)</svg>", html, re.S):
            if snippet in match.group(0):
                return match.group(1), match.group(2)
    raise SystemExit(f"icon not found: {snippet}")


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def color(value):
    if value in (None, "none"):
        return None
    if value == "currentColor":
        return INK_TINT
    return "#FF" + value.lstrip("#").upper()


def rect_path(a):
    x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
    r = float(a.get("rx", 0))
    if r == 0:
        return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z"
    return (
        f"M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g} 0,0 1,{r:g},{r:g}v{h - 2 * r:g}"
        f"a{r:g},{r:g} 0,0 1,{-r:g},{r:g}h{-(w - 2 * r):g}a{r:g},{r:g} 0,0 1,{-r:g},{-r:g}"
        f"v{-(h - 2 * r):g}a{r:g},{r:g} 0,0 1,{r:g},{-r:g}z"
    )


def circle_path(a):
    cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
    return f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0,1 1,{2 * r:g},0a{r:g},{r:g} 0,1 1,{-2 * r:g},0z"


def polygon_points(d):
    nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", d)]
    points = list(zip(nums[0::2], nums[1::2]))
    return points + [points[0]]


def dash_path(d, dash, gap):
    """Split a closed polygon (M/L/Z only) into dash segments along its perimeter."""
    points = polygon_points(d)
    out, pattern, pos, drawing = [], [dash, gap], 0.0, True
    remaining = pattern[0]
    for (x1, y1), (x2, y2) in zip(points, points[1:]):
        length = math.hypot(x2 - x1, y2 - y1)
        start = 0.0
        while start < length - 1e-6:
            step = min(remaining, length - start)
            if drawing:
                t0, t1 = start / length, (start + step) / length
                out.append(
                    f"M{x1 + (x2 - x1) * t0:.2f},{y1 + (y2 - y1) * t0:.2f}"
                    f"L{x1 + (x2 - x1) * t1:.2f},{y1 + (y2 - y1) * t1:.2f}"
                )
            start += step
            remaining -= step
            if remaining <= 1e-6:
                drawing = not drawing
                remaining = pattern[0] if drawing else pattern[1]
    return "".join(out)


def vector(svg_attrs, body):
    view_box = attrs(svg_attrs).get("sc-camel-view-box") or attrs(svg_attrs).get("viewBox", "0 0 32 32")
    _, _, vw, vh = (float(v) for v in view_box.split())
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/extract_icons.py from design/screens. Don't edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{vw:g}dp"',
        f'    android:height="{vh:g}dp"',
        f'    android:viewportWidth="{vw:g}"',
        f'    android:viewportHeight="{vh:g}">',
    ]
    for tag, element in re.findall(r"<(path|rect|circle)\b([^>]*)>", body):
        a = attrs(element)
        data = {"path": lambda: a["d"], "rect": lambda: rect_path(a), "circle": lambda: circle_path(a)}[tag]()
        fill, stroke = color(a.get("fill")), color(a.get("stroke"))
        dashed = "stroke-dasharray" in a
        if dashed and fill:
            lines.append(f'    <path android:fillColor="{fill}" android:pathData="{data}" />')
            fill = None
        if dashed:
            dash, gap = (float(v) for v in a["stroke-dasharray"].split())
            data = dash_path(a["d"], dash, gap)
        path = ["    <path"]
        if fill:
            path.append(f'        android:fillColor="{fill}"')
        if stroke:
            path.append(f'        android:strokeColor="{stroke}"')
            path.append(f'        android:strokeWidth="{float(a.get("stroke-width", 1)):g}"')
            if a.get("stroke-linecap") or dashed:
                path.append(f'        android:strokeLineCap="{a.get("stroke-linecap", "round")}"')
            if a.get("stroke-linejoin"):
                path.append(f'        android:strokeLineJoin="{a["stroke-linejoin"]}"')
        path.append(f'        android:pathData="{data}" />')
        lines.append("\n".join(path))
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    stale = []
    for name, snippet in ICONS.items():
        content = vector(*find_svg(snippet))
        target = os.path.join(OUT, f"ic_{name}.xml")
        if check:
            if not os.path.exists(target) or open(target, encoding="utf-8").read() != content:
                stale.append(target)
        else:
            with open(target, "w", encoding="utf-8") as f:
                f.write(content)
    if stale:
        raise SystemExit("stale icons: " + ", ".join(stale))
    print(f"{len(ICONS)} icons {'checked' if check else 'written'} in {OUT}")


if __name__ == "__main__":
    main()
